// Generates src/mocks/grade6.generated.ts from curriculum/grade6/<subject>/{path,manifest}.json.
// Run: npm run gen:grade6   (re-run whenever a path.json or manifest.json changes)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
// Same order as SUBJECTS in src/mocks/concepts.ts.
const SUBJECTS = ['maths', 'science', 'sinhala', 'english', 'ict'];
const KINDS = new Set(['lesson', 'practice', 'quiz', 'revision']);

const read = (subject, file) => JSON.parse(readFileSync(join(root, 'curriculum', 'grade6', subject, file), 'utf8'));
const errors = [];
const concepts = [];
const docs = [];

for (const subject of SUBJECTS) {
  const path = read(subject, 'path.json');
  if (path.subject !== subject || path.grade !== 6) errors.push(`${subject}: subject/grade mismatch`);
  const ids = new Set(path.concepts.map((c) => c.id));
  // Teaching order: term first, then file order (Array.prototype.sort is stable).
  const ordered = path.concepts.map((c, i) => ({ c, i })).sort((a, b) => a.c.term - b.c.term || a.i - b.i);
  for (const { c } of ordered) {
    for (const p of c.prerequisiteIds ?? []) if (!ids.has(p)) errors.push(`${c.id}: unknown prerequisite ${p}`);
    for (const s of c.steps) if (!KINDS.has(s.kind)) errors.push(`${c.id}: bad step kind ${s.kind}`);
    if (![1, 2, 3].includes(c.term)) errors.push(`${c.id}: bad term ${c.term}`);
    concepts.push({
      id: c.id,
      subject,
      term: c.term,
      unit: c.unit,
      textbookRef: c.textbookRef,
      prerequisiteIds: c.prerequisiteIds ?? [],
      steps: c.steps.map((s) => ({ kind: s.kind, estimatedMinutes: s.estimatedMinutes })),
      titleEn: c.title_en,
      ...(c.title_si ? { titleSi: c.title_si } : {}),
    });
  }

  // Admin curriculum docs: the official documents that were actually obtained (file != null).
  read(subject, 'manifest.json')
    .filter((d) => d.file)
    .forEach((d, i) => docs.push({ id: `cur-${subject}-${i + 1}`, subject, kind: d.kind, title: d.title, edition: d.edition ?? '' }));
}

if (errors.length) {
  console.error(errors.join('\n'));
  process.exit(1);
}

const out = `// GENERATED by scripts/gen-grade6.mjs from curriculum/grade6/*/{path,manifest}.json. Do not edit by hand.
export type G6StepKind = 'lesson' | 'practice' | 'quiz' | 'revision';

export interface G6Concept {
  id: string;
  subject: string;
  term: 1 | 2 | 3;
  unit: string;
  textbookRef: string;
  prerequisiteIds: string[];
  steps: { kind: G6StepKind; estimatedMinutes: number }[];
  titleEn: string;
  titleSi?: string;
}

export interface G6SourceDoc {
  id: string;
  subject: string;
  kind: 'textbook' | 'teachers_guide' | 'syllabus' | 'other';
  title: string;
  edition: string;
}

/** Grade 6 concepts per subject, in teaching order (term, then textbook order). */
export const G6_CONCEPTS: G6Concept[] = ${JSON.stringify(concepts, null, 2)};

/** Official source documents obtained for the Grade 6 paths (from each manifest.json). */
export const G6_SOURCE_DOCS: G6SourceDoc[] = ${JSON.stringify(docs, null, 2)};
`;
writeFileSync(join(root, 'src', 'mocks', 'grade6.generated.ts'), out);
console.log(`gen:grade6 ok: ${concepts.length} concepts, ${docs.length} source docs`);
